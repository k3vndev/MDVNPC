package com.mdvcraft.mdvnpc.api;

/** Gestos que imitan lo que haría un jugador real. */
public enum CompanionGesture {
    /** Saludo: se agacha y levanta varias veces mientras mueve el brazo (~1 s). */
    WAVE,
    /** Un movimiento de brazo, como un golpe al aire. */
    SWING,
    /** Se agacha y se levanta una vez. */
    CROUCH
}
